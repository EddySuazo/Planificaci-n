export function normalizeCedula(input: string): string {
  const digits = input.replace(/\D/g, '');
  if (digits.length <= 3) return digits;
  if (digits.length <= 10) return `${digits.slice(0, 3)}-${digits.slice(3)}`;
  return `${digits.slice(0, 3)}-${digits.slice(3, 10)}-${digits.slice(10, 11)}`;
}

export function findTeacherInCensus(cedulaInput: string): TeacherCensusRecord | undefined {
  const cleanInput = cedulaInput.replace(/\D/g, '');
  return DOMINICAN_TEACHER_CENSUS.find(t => t.cedula.replace(/\D/g, '') === cleanInput);
}
